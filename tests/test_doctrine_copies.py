def locked_source(name):
    path = Path(subprocess.check_output([
        "nix-store", "--print-fixed-path", "--recursive", "sha256",
        LOCK["nodes"][name]["locked"]["narHash"], "source",
    ], text=True).strip())
    assert path.is_dir(), f"locked {name} is not cached; prefetch outside this offline test"
    return str(path)


