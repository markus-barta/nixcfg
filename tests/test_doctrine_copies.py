def evaluate(enabled=None, legacy=False, module=None, host=None, kernel_overrides=None, reject=False):
    args = {
        "nixpkgs": NIXPKGS, "publicSource": str(Path(PUBLIC).parents[1]),
        "selfRev": "1" * 40, "legacy": legacy, "doctrineEnabled": enabled,
    }
    if module:
        args["modulePath"] = str(module)
    if host:
        args["hostHome"] = str(host)
    if kernel_overrides:
        args["kernelOverrides"] = kernel_overrides
    expression = "import ./tests/aeon-operator-mac-eval.nix (builtins.fromJSON " + json.dumps(json.dumps(args)) + ")"
    result = subprocess.run([
        "nix-instantiate", "--eval", "--strict", "--json", "--expr", expression,
    ], cwd=REPO, capture_output=True, text=True)
    if reject:
        assert result.returncode != 0 and "Doctrine copies require" in result.stderr, "invalid kernel sources accepted"
        return
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


def asset(value, name):
    match = ASSET.fullmatch(value)
    assert match and match[1] == name, f"unexpected writeText fixture: {name}"
    return match[2]


