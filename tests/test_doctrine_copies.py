def verify_personal_refusals(cfg):
    cases = {
        "no-begin": END + b"\nforeign\n",
        "no-end": BEGIN + b"\nforeign\n",
        "duplicate-begin": BEGIN + b"\n" + PREFIX,
        "duplicate-end": PREFIX + END + b"\n",
        "reversed": END + b"\n" + BEGIN + b"\n",
        "inline": b"inline " + BEGIN + b"\n" + END + b"\n",
        "symlink": None, "broken-symlink": None, "directory": None, "fifo": None,
        "parent-symlink": None, "missing": None,
    }
    with tempfile.TemporaryDirectory(prefix="ops756-refusals-") as temporary:
        root = Path(temporary).resolve()
        assets = root / "assets"
        assets.mkdir()
        for kind, content in cases.items():
            home = root / kind
            dest = home / CODEX
            dest.parent.mkdir(parents=True)
            referent = root / (kind + "-referent")
            if content is not None:
                dest.write_bytes(content)
            elif kind in ("symlink", "broken-symlink"):
                if kind == "symlink":
                    referent.write_bytes(PREFIX + b"\nforeign\n")
                dest.symlink_to(referent)
            elif kind == "directory":
                dest.mkdir()
            elif kind == "fifo":
                os.mkfifo(dest)
            elif kind == "parent-symlink":
                dest.parent.rmdir()
                referent.mkdir()
                (referent / "AGENTS.md").write_bytes(PREFIX + b"\nforeign\n")
                dest.parent.symlink_to(referent, target_is_directory=True)
            def identity():
                info = dest.lstat() if os.path.lexists(dest) else None
                return (info.st_mode, info.st_ino, info.st_mtime_ns) if info else None

            before = identity()
            result = run_activation(cfg, home, assets)
            assert "WARNING" in result.stderr and str(dest) in result.stderr, f"missing refusal warning: {kind}"
            after = identity()
            assert before == after, f"refused target changed: {kind}"
            if content is not None:
                assert dest.read_bytes() == content, f"refused marker bytes changed: {kind}"
            if kind == "symlink":
                assert referent.read_bytes() == PREFIX + b"\nforeign\n"
            if kind == "parent-symlink":
                assert (referent / "AGENTS.md").read_bytes() == PREFIX + b"\nforeign\n"
            assert not list(home.rglob("*.pre-hm-*")), f"refusal created a backup: {kind}"
            assert (home / COWORK).read_bytes() == STANDARD, f"refusal stopped later target: {kind}"
            status = json.loads((home / STATUS).read_text())["targets"]
            assert status[0]["outcome"].startswith("skipped:"), f"refusal status missing: {kind}"
    print("T130: missing/duplicated/malformed markers, symlink/non-regular target and parent refusals warn and continue passed")


